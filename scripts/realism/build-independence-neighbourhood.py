"""Inventory the immediate Independence Square ring, before further Osu expansion.
Native plates remain separate from photo-estimated height/facade annotations.
Unknown neighbours retain native heights; no inferred business identities.
"""
import csv,gzip,json,math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
BOUNDS=[-.1976,5.5453,-.1905,5.5528]
RETAINED={339732242,339732246,339732248,339732250,339732254,339732256,339732258,339732260,339732244,339732252}
SPECIAL={339732240:('stadium','stadium-west',22),339732262:('stadium','stadium-bowl',18.5),596516558:('volta','volta',44.8),588620800:('water','water',15),312724288:('club','club',7.5),16546541:('finance','finance',20),596516562:('finance','finance-annex',20),1215731838:('finance','finance-link',16),1017656842:('commission','commission-front',24),1028531778:('commission','commission-rear',24)}
def points(c):
 if isinstance(c[0],(int,float)):yield c
 else:
  for v in c:yield from points(v)
context={}
for layer in ['building','road','landuse']:
 rows=[]
 for path in sorted((ROOT/'public/maps/accra-v1').glob('source-'+layer+'-*.geojson.gz')):
  for f in json.load(gzip.open(path,'rt'))['features']:
   ps=list(points(f['geometry']['coordinates']));xs,ys=zip(*ps)
   include=all(BOUNDS[0]<=p[0]<=BOUNDS[2] and BOUNDS[1]<=p[1]<=BOUNDS[3] for p in ps) if layer=='building' else max(xs)>=BOUNDS[0] and min(xs)<=BOUNDS[2] and max(ys)>=BOUNDS[1] and min(ys)<=BOUNDS[3]
   if include:rows.append(f)
 context[layer+'s']=rows
assert len(context['buildings'])==158
assert RETAINED<={f['id'] for f in context['buildings']}
bs=[]
for f in context['buildings']:
 if f['id'] in RETAINED:continue
 assert f['geometry']['type']=='Polygon'
 r=f['geometry']['coordinates'];xs,ys=zip(*r[0][:-1]);cx,cy=(min(xs)+max(xs))/2,(min(ys)+max(ys))/2
 if f['id'] in SPECIAL:zone,family,height=SPECIAL[f['id']]
 else:
  zone=('west' if cx<-.1955 else 'east')+('-north' if cy>5.551 else '-south')
  family='mapped-context';height=f['properties']['height']
 bs.append(dict(id=f['id'],name=f['properties']['name'],zone=zone,family=family,rings=r,wallHeight=height,roofRise=2.4 if family=='club' else 0,roof='hip' if family=='club' else 'flat',wallColor='#c7c2af',roofColor='#898d84',geometrySource='native-building-polygon',appearanceEvidence=('native massing; frontage-derived facade, rear unverified' if family=='commission-rear' else 'native height and overhead massing only; hidden elevations unverified' if family in {'mapped-context','finance-link'} else 'dated facade reference; current condition and exact dimensions unverified'),dimensionsEstimated=True,facadesEstimated=True))
land=[f for f in context['landuses'] if f['id'] in {23053858,339732280,1167623806,1171837618,1171837620,1202584024,1215781800,1215781802,1215781804}]
out='// Generated by build-independence-neighbourhood.py. OSM/ODbL; photo dimensions estimated.\n'
for key,v in [('CIVIC_BOUNDS',BOUNDS),('CIVIC_RETAINED_IDS',sorted(RETAINED)),('CIVIC_BUILDINGS',bs),('CIVIC_LAND',land),('CIVIC_ROADS',[dict(id=f['id'],coordinates=f['geometry']['coordinates'],**f['properties']) for f in context['roads'] if f['geometry']['type']=='LineString'])]:out+='export const '+key+'='+json.dumps(v,separators=(',',':'))+';\n'
(ROOT/'public/game/independence-neighbourhood-map.js').write_text(out)
(ROOT/'tests/fixtures/independence-neighbourhood-context.json').write_text(json.dumps(context,separators=(',',':'))+'\n')
with (ROOT/'docs/realism/independence-neighbourhood-buildings.csv').open('w') as fp:
 w=csv.writer(fp);w.writerow(['source_id','name','zone','scope','geometry_source','height_m','height_evidence','appearance_evidence','status','remaining_work'])
 for f in context['buildings']:
  b=next((b for b in bs if b['id']==f['id']),None)
  w.writerow([f['id'],f['properties']['name'],b['zone'] if b else 'square-core',b['family'] if b else 'existing-authored-monument-or-stand','native-building-polygon',b['wallHeight'] if b else f['properties']['height'],'photo estimate' if f['id'] in SPECIAL and f['id'] not in {16546541,596516562,1215731838} else 'native tag; not surveyed',b['appearanceEvidence'] if b else 'existing dated reference register','Partial','Current dated facade/roof evidence, measured heights, hidden elevations, access and device acceptance'])
print(len(bs),'new/updated native exteriors;',len(RETAINED),'retained core records; 158 records accounted for')
