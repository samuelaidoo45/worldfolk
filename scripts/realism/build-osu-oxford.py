"""Pin the first Osu block to native data, preserving the distinction between
mall property boundary and its photo-estimated street-wing building outline.
No live map calls or reference imagery are required by the renderer.
"""
import gzip,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
BOUNDS=[-.1831,5.5592,-.18145,5.56165]
IDS={1179058850,1179058852,1179058864}
def points(cs):
 if isinstance(cs[0],(float,int)):yield cs
 else:
  for c in cs:yield from points(c)
context={}
for layer in ['building','road']:
 records=[]
 for path in sorted((ROOT/'public/maps/accra-v1').glob('source-'+layer+'-*.geojson.gz')):
  for f in json.load(gzip.open(path,'rt'))['features']:
   ps=list(points(f['geometry']['coordinates']));xs,ys=zip(*ps)
   if max(xs)>=BOUNDS[0] and min(xs)<=BOUNDS[2] and max(ys)>=BOUNDS[1] and min(ys)<=BOUNDS[3]:records.append(f)
 context[layer+'s']=records
rings={str(f['id']):f['geometry']['coordinates'][0] for f in context['buildings'] if f['id'] in IDS}
assert len(rings)==3
# OSM way 259080346, read 2026-10-20: shop=mall (NOT building=yes).
# Keep the entire property ring as evidence, never extrude it as one building.
mallBoundary=[[-.1821509,5.560676],[-.1822223,5.5602763],[-.1822296,5.5602356],[-.1829536,5.5603638],[-.182875,5.5608041],[-.1827626,5.5607842],[-.1821509,5.560676]]
# Street wing: setback from that frontage, with a shallow depth inferred from
# August 2024 Street View. Rear shop/building records remain native and separate.
mallWing=[[-.1821689,5.560669],[-.1822363,5.560292],[-.182404,5.560322],[-.1823366,5.560699],[-.1821689,5.560669]]
out='// Generated by scripts/realism/build-osu-oxford.py. See docs/realism/osu-oxford.md.\n'
for name,value in [('OSU_RINGS',rings),('OSU_MALL_PROPERTY',mallBoundary),('OSU_MALL_WING',mallWing)]:out+='export const '+name+'='+json.dumps(value,separators=(',',':'))+';\n'
(ROOT/'public/game/osu-oxford-map.js').write_text(out)
(ROOT/'tests/fixtures/osu-oxford-context.json').write_text(json.dumps(context,separators=(',',':'))+'\n')
print('Osu: 3 native building plates + separately annotated mall street wing')
