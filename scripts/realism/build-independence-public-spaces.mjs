// Bake parcel detail once; runtime never performs this nested geometry survey.
import fs from 'node:fs/promises';import {createHash} from 'node:crypto';
import {CIVIC_ROADS} from '../../public/game/independence-neighbourhood-map.js';
import {areaInside} from '../../public/game/mahama-neighbourhood-data.js';
import {PARK_RING,STADIUM_RING,SPACE_GATES,SPACE_PATHS,spaceRoadClear,spaceBuildingClear,spaceObstacle} from '../../public/game/independence-public-space-data.js';
import {distanceMetres,projectOnSegment,bearingTo} from '../../public/game/motion.js';
import {roadWidth} from '../../public/game/street-safety.js';
const midpoint=(a,b)=>a.map((n,k)=>(n+b[k])/2);
function inset(p,center,metres){const d=distanceMetres(p,center);return p.map((n,k)=>n+(center[k]-n)*Math.min(.2,metres/(d||1)));}
function perimeter(ring,zone){
 const ps=ring.slice(0,-1),center=[0,1].map(k=>ps.reduce((n,p)=>n+p[k],0)/ps.length),lines=[];
 for(let i=1;i<ring.length;i++){
  const a=inset(ring[i-1],center,1.4),b=inset(ring[i],center,1.4),n=Math.ceil(distanceMetres(a,b)/3.5);
  for(let j=0;j<n;j++){
   const A=a.map((p,k)=>p+(b[k]-p)*j/n),B=a.map((p,k)=>p+(b[k]-p)*(j+1)/n),m=midpoint(A,B);
   if(![A,m,B].every(p=>areaInside(p,[ring])&&spaceRoadClear(p,.4)&&spaceBuildingClear(p,.45)))continue;
   // Leave actual openings, including every native footpath crossing the fence.
   if(SPACE_GATES[zone].some(g=>projectOnSegment(g,A,B).distance<(zone==='park'?4.5:7)))continue;
   if(CIVIC_ROADS.filter(r=>['path','pedestrian'].includes(r.class)).some(r=>r.coordinates.slice(1).some((p,k)=>[A,m,B].some(q=>projectOnSegment(q,r.coordinates[k],p).distance<2))))continue;
   lines.push({a:A,b:B,zone,height:zone==='park'?1.85:2.8,solid:zone==='stadium'&&i>=10});
  }
 }
 return lines;
}
const SPACE_FENCES=[...perimeter(PARK_RING,'park'),...perimeter(STADIUM_RING,'stadium')];
const SPACE_VERGES=[];
for(const f of SPACE_FENCES.filter(f=>f.zone==='stadium'&&f.solid)){
 const c=[-.1923,5.5515],m=midpoint(f.a,f.b),distance=distanceMetres(m,c),p=m.map((n,k)=>n+(n-c[k])*3/(distance||1));
 const a=f.a.map((n,k)=>n+p[k]-m[k]),b=f.b.map((n,k)=>n+p[k]-m[k]);
 if([a,midpoint(a,b),b].every(p=>spaceRoadClear(p,1.5)&&spaceBuildingClear(p,1.5)))SPACE_VERGES.push({a,b,width:2.8});
}
const SPACE_PATH_PIECES=[];
for(const path of SPACE_PATHS)for(let i=1;i<path.length;i++){
 const a=path[i-1],b=path[i],n=Math.ceil(distanceMetres(a,b)/2);
 for(let j=0;j<n;j++){const A=a.map((p,k)=>p+(b[k]-p)*j/n),B=a.map((p,k)=>p+(b[k]-p)*(j+1)/n);
  if([A,midpoint(A,B),B].every(p=>areaInside(p,[PARK_RING])&&spaceRoadClear(p,1.2)&&spaceBuildingClear(p,1.2)&&!spaceObstacle(p,1.2)))SPACE_PATH_PIECES.push({a:A,b:B,width:2});
 }
}
const SPACE_CROSSINGS=[];
for(const path of CIVIC_ROADS.filter(r=>[498865981,570170633,607890897].includes(r.id)))for(let i=1;i<path.coordinates.length;i++){
 const a=path.coordinates[i-1],b=path.coordinates[i],v=b.map((n,k)=>n-a[k]);
 for(const road of CIVIC_ROADS.filter(r=>!['path','pedestrian','steps','cycleway'].includes(r.class)))for(let j=1;j<road.coordinates.length;j++){
  const c=road.coordinates[j-1],d=road.coordinates[j],w=d.map((n,k)=>n-c[k]),cross=(u,v)=>u[0]*v[1]-u[1]*v[0],den=cross(v,w);if(Math.abs(den)<1e-15)continue;
  const delta=c.map((n,k)=>n-a[k]),t=cross(delta,w)/den,u=cross(delta,v)/den;if(t<0||t>1||u<0||u>1)continue;
  const position=a.map((n,k)=>n+v[k]*t);if(distanceMetres(position,[-.1919,5.5498])>180||!spaceBuildingClear(position,2)||SPACE_CROSSINGS.some(p=>distanceMetres(p.position,position)<12))continue;
  // Restrict paint to the two connecting 28 February Road approaches; do not
  // turn every noded service-road/path junction into another zebra crossing.
  if([169135204,447597823].includes(road.id))SPACE_CROSSINGS.push({position,width:roadWidth(road.class),heading:bearingTo(c,d),pathId:path.id,roadId:road.id,paintEstimated:true});
 }
}

const root=new URL('../../',import.meta.url),sources=['public/game/independence-public-space-data.js','public/game/independence-neighbourhood-map.js','scripts/realism/build-independence-public-spaces.mjs'],hashes={};
for(const path of sources)hashes[path]=createHash('sha256').update(await fs.readFile(new URL(path,root))).digest('hex');
let out='// Generated by scripts/realism/build-independence-public-spaces.mjs. Layout/paint estimated; native parcels retained.\n';
for(const [name,data] of Object.entries({SPACE_FENCES,SPACE_VERGES,SPACE_PATH_PIECES,SPACE_CROSSINGS,SPACE_LAYOUT_SOURCES:hashes}))out+='export const '+name+'='+JSON.stringify(data)+';\n';
await fs.writeFile(new URL('public/game/independence-public-space-map.js',root),out);
console.log('Baked',SPACE_FENCES.length,'fence sections,',SPACE_PATH_PIECES.length,'path sections,',SPACE_CROSSINGS.length,'crossings');
